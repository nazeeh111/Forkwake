import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const dispatch=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
const ending=JSON.parse(await fs.readFile(process.argv[3],'utf8'));
const paused=dispatch.final.report,finished=ending.final.report;
assert.equal(paused.pendingLabel,'dispatch');
assert.equal(paused.origin.state,'captured');
assert.equal(paused.origin.lastDecision,false);
assert.equal(paused.origin.pendingOrdinal,4);
assert.ok(paused.origin.frames.some(f=>f.functionName==='dispatchOrder'&&f.sourceBound));
assert.ok(paused.origin.frames.some(f=>f.functionName==='checkout'&&f.sourceBound));
assert.equal(finished.resultI32,1);
assert.equal(finished.origin.lastDecision,true);
assert.equal(finished.origin.pendingOrdinal,4);
assert.equal(finished.origin.sourceSha256,paused.origin.sourceSha256);
assert.equal(finished.entryCount,1);
const ledger=JSON.parse(finished.output);
assert.equal(ledger.reserved,true);assert.equal(ledger.paid,false);assert.equal(ledger.dispatched,true);
console.log('Installed Origin cut preserves actual callers and reproduces unpaid dispatch after a new-key portable reopen.');
